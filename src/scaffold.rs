/// POSIX single-quote so sh can never interpret the embedded value
/// (`$(...)`, backticks, quotes). A literal `'` becomes `'\''`.
fn sh_single_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

fn portable_hook_script(native_hook_abs: &str) -> Result<String> {
    // Prefer absolute native path so PATH hijack cannot supply a fake `doxguard`.
    // Fall back to git-dir relative cache, then refuse rather than trusting bare PATH.
    if native_hook_abs.contains(['\n', '\r', '\0']) {
        bail!("hook path contains control characters; refusing to generate the hook script");
    }
    Ok(format!(
        r#"#!/usr/bin/env sh
# Generated by doxguard. The watchlist remains outside this repository.
git_dir=$(git rev-parse --git-dir) || exit 2
native_abs={native}
if [ -x "$native_abs" ]; then
  exec "$native_abs"
fi
if [ -x "$git_dir/doxguard/hooks/pre-commit" ]; then
  exec "$git_dir/doxguard/hooks/pre-commit"
fi
echo "doxguard: native pre-commit binary missing; run: doxguard install-hooks" >&2
exit 2
"#,
        native = sh_single_quote(&native_hook_abs.replace('\\', "/"))
    ))
}

