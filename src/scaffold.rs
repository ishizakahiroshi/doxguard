#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ActionStatus {
    Created,
    Skipped,
    Configured,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScaffoldAction {
    pub path: String,
    pub status: ActionStatus,
    pub detail: Option<String>,
}

